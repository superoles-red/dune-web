# ---------------------------------------------------------------------------
# Page / dispatch emission.
# ---------------------------------------------------------------------------
PAGE_SHIFT = 12               # 4 KiB pages
PAGE_SIZE = 1 << PAGE_SHIFT
SLOT_SHIFT = 1                # every 68000 instruction starts on an even address
SLOTS_PER_PAGE = PAGE_SIZE >> SLOT_SHIFT  # 2048

CHUNK_SHIFT = 6               # 64 slots per br_table chunk
SLOTS_PER_CHUNK = 1 << CHUNK_SHIFT  # 64
CHUNKS_PER_PAGE = SLOTS_PER_PAGE // SLOTS_PER_CHUNK  # 32

PAGE_GROUP_SHIFT = 4          # 16 groups x 16 pages = 256 = one 1 MiB ROM
PAGE_GROUPS = 16
PAGES_PER_GROUP = 16

RAM_PAGE_COUNT = 16           # pages 0xFF0..0xFFF


def slot_of(pc: int) -> int:
    return (pc & (PAGE_SIZE - 1)) >> SLOT_SHIFT


def emit_chunk(ctx: Ctx, chunk_index: int, handlers):
    """Emit a two-level slot dispatch for one 64-slot chunk of a page.

    Layout (all handlers inline, no per-instruction function call):

        block $out2
          block $s63 ... block $s0
            br_table (slot & 63) -> s0..s63 | out2
          end
          <handler slot 0>  (ends with return)
          end
          <handler slot 1>
          ...
        end
        <chunk default: fail + return>
    """
    c = ctx.c
    for _ in range(SLOTS_PER_CHUNK + 1):  # $out2 + $s63..$s0
        c.block()
    ctx.lg("slot")
    c.i32_const(SLOTS_PER_CHUNK - 1)
    c.i32_and()
    entries = []
    for inner in range(SLOTS_PER_CHUNK):
        entries.append(inner if inner in handlers else SLOTS_PER_CHUNK)
    c.br_table(entries, SLOTS_PER_CHUNK)
    for inner in range(SLOTS_PER_CHUNK):
        c.end()  # closes block $s<inner>; handler body starts here
        inst = handlers.get(inner)
        if inst is not None:
            HANDLERS[inst["kind"]](ctx, inst)
    c.end()  # $out2
    ctx.fail(FAIL_UNTRANSLATED)
    c.return_()


def emit_page(func: w.Func, handlers_by_slot):
    """Emit one page function ``(c: i32, pc: i32) -> void``.

    Level 1 dispatches on ``slot >> 6`` (32 chunks); level 2 inside the chunk
    dispatches on ``slot & 63``.  Missing chunks/slots fall through to ``fail``.
    """
    ctx = Ctx(
        func.code,
        params=("c", "pc"),
        locals_=[
            ("slot", I32),
            ("addr", I32),
            ("val", I32),
            ("res", I32),
            ("cond", I32),
        ],
    )
    func.locals = ctx._types
    c = ctx.c
    # uint32_t slot = ((pc & 0xfff) >> 1);
    ctx.lg("pc")
    c.i32_const(PAGE_SIZE - 1)
    c.i32_and()
    c.i32_const(SLOT_SHIFT)
    c.i32_shr_u()
    ctx.ls("slot")

    chunks = {}
    for slot, inst in handlers_by_slot.items():
        chunks.setdefault(slot >> CHUNK_SHIFT, {})[slot & (SLOTS_PER_CHUNK - 1)] = inst

    # Level 1: block $out, then block $chunk31..$chunk0 (innermost first code).
    for _ in range(CHUNKS_PER_PAGE + 1):
        c.block()
    ctx.lg("slot")
    c.i32_const(CHUNK_SHIFT)
    c.i32_shr_u()
    entries = [
        chunk if chunk in chunks else CHUNKS_PER_PAGE
        for chunk in range(CHUNKS_PER_PAGE)
    ]
    c.br_table(entries, CHUNKS_PER_PAGE)
    for chunk in range(CHUNKS_PER_PAGE):
        c.end()
        if chunk in chunks:
            emit_chunk(ctx, chunk, chunks[chunk])
    c.end()  # $out
    ctx.fail(FAIL_UNTRANSLATED)
    c.return_()


def emit_translated_step(func: w.Func, page_funcs, ram_funcs):
    """Emit ``translated_step(c: i32) -> void`` — the entry called by runtime."""
    ctx = Ctx(func.code, params=("c",), locals_=[("pc", I32), ("page", I32)])
    func.locals = ctx._types
    c = ctx.c
    ctx.load(OFF_PC)
    ctx.ls("pc")
    # if (pc >= 0x1000000) fail(FAIL_BAD_PC);
    ctx.lg("pc")
    c.i32_const(0x1000000)
    c.i32_ge_u()
    c.if_()
    ctx.fail(FAIL_BAD_PC)
    c.return_()
    c.end_()
    # if (pc & 1) fail(FAIL_ODD_PC);
    ctx.lg("pc")
    c.i32_const(1)
    c.i32_and()
    c.if_()
    ctx.fail(FAIL_ODD_PC)
    c.return_()
    c.end_()
    # page = pc >> 12
    ctx.lg("pc")
    c.i32_const(PAGE_SHIFT)
    c.i32_shr_u()
    ctx.ls("page")
    # if (page < 0x100) { ROM region } else { RAM region / fail }
    ctx.lg("page")
    c.i32_const(0x100)
    c.i32_lt_u()
    c.if_()
    # ROM: group = page >> 4, inner = page & 15 -> page function
    emit_region_dispatch(ctx, page_funcs, base=0, groups=16, per_group=16,
                        fail_reason=FAIL_UNTRANSLATED, group_shift=4,
                        inner_mask=15, call_arg="pc")
    c.else_()
    ctx.lg("page")
    c.i32_const(0xFF0)
    c.i32_ge_u()
    c.if_()
    # RAM: index = page & 0xf
    emit_region_dispatch(ctx, ram_funcs, base=0xFF0, groups=1, per_group=16,
                        fail_reason=FAIL_UNMAPPED, group_shift=None,
                        inner_mask=15, call_arg="pc")
    c.else_()
    ctx.fail(FAIL_UNMAPPED)
    c.return_()
    c.end_()
    c.end_()


def emit_region_dispatch(ctx: Ctx, page_funcs, base, groups, per_group, fail_reason,
                         group_shift, inner_mask, call_arg="pc"):
    """Emit a two-level ``br_table`` over ``groups * per_group`` page slots.

    ``page_funcs`` maps absolute page number -> Func.  The dispatcher is
    complete (every slot has a block); present pages call their function and
    return, empty slots fall through to ``fail``.  ``group_shift`` and
    ``inner_mask`` transform the ``page`` local into the two table indices;
    the page function is called with ``call_arg`` (the full PC), not the page.
    """
    c = ctx.c
    page_local = "page"

    for _ in range(groups + 1):
        c.block()
    if group_shift:
        ctx.lg(page_local)
        c.i32_const(group_shift)
        c.i32_shr_u()
    else:
        c.i32_const(0)
    entries = []
    for group in range(groups):
        present = any(
            (base + group * per_group + inner) in page_funcs
            for inner in range(per_group)
        )
        entries.append(group if present else groups)
    c.br_table(entries, groups)
    for group in range(groups):
        c.end()
        present = any(
            (base + group * per_group + inner) in page_funcs
            for inner in range(per_group)
        )
        if not present:
            continue  # unreachable: no br_table entry targets this label
        for _ in range(per_group + 1):
            c.block()
        ctx.lg(page_local)
        c.i32_const(inner_mask)
        c.i32_and()
        entries = []
        for inner in range(per_group):
            page = base + group * per_group + inner
            entries.append(inner if page in page_funcs else per_group)
        c.br_table(entries, per_group)
        for inner in range(per_group):
            c.end()
            page = base + group * per_group + inner
            if page in page_funcs:
                ctx.push_c()
                ctx.lg(call_arg)
                c.call(page_funcs[page].index)
                c.return_()
        c.end()  # inner $out
        ctx.fail(fail_reason)
        c.return_()
    c.end()  # outer $out
    ctx.fail(fail_reason)
    c.return_()


def emit_stress_dispatch(func: w.Func):
    """``stress_dispatch(slot: i32) -> i32`` — the production dispatch shape at
    full width: 2048 slots, 32 chunks x 64 slots.  Returns the handler id (the
    slot itself) or -1 for a missing slot.  Every slot is present except
    ``slot % 97 == 0`` so both the handler path and the default path are tested.
    """
    c = func.code
    present = {slot for slot in range(SLOTS_PER_PAGE) if slot % 97 != 0}
    blocks = CHUNKS_PER_PAGE + 1
    for _ in range(blocks):
        c.block()
    c.local_get(0)  # parameter slot
    c.i32_const(CHUNK_SHIFT)
    c.i32_shr_u()
    entries = [
        chunk if any(slot >> CHUNK_SHIFT == chunk for slot in present) else blocks - 1
        for chunk in range(CHUNKS_PER_PAGE)
    ]
    c.br_table(entries, blocks - 1)
    for chunk in range(CHUNKS_PER_PAGE):
        c.end()
        chunk_present = [s for s in present if s >> CHUNK_SHIFT == chunk]
        if not chunk_present:
            continue
        for _ in range(SLOTS_PER_CHUNK + 1):
            c.block()
        c.local_get(0)
        c.i32_const(SLOTS_PER_CHUNK - 1)
        c.i32_and()
        inner_entries = []
        for inner in range(SLOTS_PER_CHUNK):
            slot = chunk * SLOTS_PER_CHUNK + inner
            inner_entries.append(inner if slot in present else SLOTS_PER_CHUNK)
        c.br_table(inner_entries, SLOTS_PER_CHUNK)
        for inner in range(SLOTS_PER_CHUNK):
            c.end()
            slot = chunk * SLOTS_PER_CHUNK + inner
            if slot in present:
                c.i32_const(slot)
                c.return_()
        c.end()  # $out2
        c.i32_const(-1)
        c.return_()
    c.end()  # $out
    c.i32_const(-1)
    c.return_()


# ---------------------------------------------------------------------------
# ABI call-overhead benchmark modules.
#
# The central ABI decision is how game.wasm calls runtime helpers.  Three
# candidates exist in WebAssembly:
#   * import the runtime.wasm export through the JS import object (simple ABI,
#     but every call crosses the JS boundary);
#   * import a funcref table, fill it with runtime.wasm exports, and use
#     call_indirect (direct wasm->wasm call, more plumbing);
#   * call a function defined inside the same module (baseline).
# poc-abi-a.wasm exports one tiny callee; poc-abi-b.wasm contains one loop per
# call style.  run_poc.mjs measures all three (and a plain JS stub for scale).
# ---------------------------------------------------------------------------
ABI_BENCH_CALLEE = "(i32)->i32: value + 1"


def build_abi_module_a():
    module = w.Module()
    callee = module.declare_func([I32], [I32])
    c = callee.code
    c.local_get(0)
    c.i32_const(1)
    c.i32_add()
    c.return_()
    module.export_func("callee", callee.index)
    return module


def _emit_abi_loop(func: w.Func, kind: str, callee_index: int, type_index: int):
    c = func.code
    # locals: i (1), acc (2)
    c.i32_const(0)
    c.local_set(1)
    c.i32_const(0)
    c.local_set(2)
    c.block()
    c.loop()
    c.local_get(1)
    c.local_get(0)
    c.i32_ge_u()
    c.br_if(1)
    c.local_get(2)
    if kind == "local":
        c.call(callee_index)
    elif kind == "import":
        c.call(0)  # env.callee (runtime.wasm export)
    elif kind == "js":
        c.call(1)  # env.js_callee (plain JS function)
    elif kind == "table":
        c.i32_const(0)  # table element index
        c.call_indirect(type_index)
    else:
        raise ValueError(kind)
    c.local_set(2)
    c.local_get(1)
    c.i32_const(1)
    c.i32_add()
    c.local_set(1)
    c.br(0)
    c.end()
    c.end()
    c.local_get(2)
    c.return_()


def build_abi_module_b():
    module = w.Module()
    module.import_func("env", "callee", [I32], [I32])     # 0: runtime export
    module.import_func("env", "js_callee", [I32], [I32])  # 1: plain JS stub
    module.import_table("env", "helper_table", 1, 1)
    callee_type = module.add_type([I32], [I32])
    local_callee = module.declare_func([I32], [I32])
    loops = {
        kind: module.declare_func([I32], [I32])
        for kind in ("local", "import", "js", "table")
    }
    c = local_callee.code
    c.local_get(0)
    c.i32_const(1)
    c.i32_add()
    c.return_()
    loops["local"].locals = [I32, I32]
    _emit_abi_loop(loops["local"], "local", local_callee.index, callee_type)
    for kind in ("import", "js", "table"):
        loops[kind].locals = [I32, I32]
        _emit_abi_loop(loops[kind], kind, 0, callee_type)
    for kind, func in loops.items():
        module.export_func("loop_" + kind, func.index)
    return module


