# ---------------------------------------------------------------------------
# Instruction handlers.  Every function emits the same statement sequence the
# C emitter would produce for the same instruction.
# ---------------------------------------------------------------------------
def op_move_d0_to_a0p(ctx: Ctx, inst):
    c = ctx.c
    ctx.set_const(OFF_INSTR_CYCLES, inst["cycles"])
    ctx.load(OFF_D)
    c.i32_const(0xFFFF)
    c.i32_and()
    ctx.ls("val")                                  # uint32_t value
    ctx.load(OFF_A)
    ctx.ls("addr")                                 # uint32_t addr
    ctx.push_c()
    ctx.lg("addr")
    c.i32_const(2)
    ctx.lg("val")
    c.call(IMP["write_mem"])
    ctx.check_fault()
    ctx.add_to_field(OFF_A, 2)
    ctx.push_c()
    ctx.lg("val")
    c.i32_const(2)
    c.call(IMP["logic_flags"])
    ctx.finish(inst["cycles"], inst["next"])


def op_addq_d0(ctx: Ctx, inst):
    c = ctx.c
    ctx.set_const(OFF_INSTR_CYCLES, inst["cycles"])
    ctx.push_c()
    ctx.load(OFF_D)
    c.i32_const(1)          # immediate
    c.i32_const(4)          # size
    c.i32_const(0)          # sub = 0
    c.i32_const(0)          # compare = 0
    c.call(IMP["arithmetic"])
    ctx.ls("res")
    ctx.push_c()
    ctx.lg("res")
    c.i32_store(offset=OFF_D)
    ctx.finish(inst["cycles"], inst["next"])


def op_subq_d3(ctx: Ctx, inst):
    c = ctx.c
    ctx.set_const(OFF_INSTR_CYCLES, inst["cycles"])
    ctx.push_c()
    ctx.load(OFF_D + 3 * 4)
    c.i32_const(1)
    c.i32_const(4)
    c.i32_const(1)          # sub = 1
    c.i32_const(0)
    c.call(IMP["arithmetic"])
    ctx.ls("res")
    ctx.push_c()
    ctx.lg("res")
    c.i32_store(offset=OFF_D + 3 * 4)
    ctx.finish(inst["cycles"], inst["next"])


def op_move_a0p_to_d1(ctx: Ctx, inst):
    c = ctx.c
    ctx.set_const(OFF_INSTR_CYCLES, inst["cycles"])
    ctx.load(OFF_A)
    ctx.ls("addr")
    ctx.push_c()
    ctx.lg("addr")
    c.i32_const(2)
    c.call(IMP["read_mem"])
    ctx.ls("val")
    ctx.check_fault()
    ctx.push_c()
    ctx.load(OFF_D + 1 * 4)
    c.i32_const(0xFFFF0000)
    c.i32_and()
    ctx.lg("val")
    c.i32_const(0xFFFF)
    c.i32_and()
    c.i32_or()
    c.i32_store(offset=OFF_D + 1 * 4)
    ctx.add_to_field(OFF_A, 2)
    ctx.push_c()
    ctx.lg("val")
    c.i32_const(2)
    c.call(IMP["logic_flags"])
    ctx.finish(inst["cycles"], inst["next"])


def op_bcc6(ctx: Ctx, inst):
    c = ctx.c
    cond = inst["condition"]
    ctx.push_c()
    c.i32_const(cond)
    c.call(IMP["condition"])
    ctx.ls("cond")
    # c->instruction_cycles = 8 + 2 * condition  (10 taken / 8 not taken)
    ctx.push_c()
    c.i32_const(8)
    ctx.lg("cond")
    c.i32_const(2)
    c.i32_mul()
    c.i32_add()
    c.i32_store(offset=OFF_INSTR_CYCLES)
    # c->pc = cond ? target : fallthrough; return;
    ctx.lg("cond")
    c.i32_eqz()
    c.if_()
    ctx.set_const(OFF_PC, inst["fallthrough"])
    c.else_()
    ctx.set_const(OFF_PC, inst["target"])
    c.end_()
    c.return_()


def op_bra(ctx: Ctx, inst):
    ctx.set_const(OFF_INSTR_CYCLES, inst["cycles"])
    ctx.set_const(OFF_PC, inst["target"])
    ctx.c.return_()


def op_moveq(ctx: Ctx, inst):
    c = ctx.c
    ctx.set_const(OFF_INSTR_CYCLES, inst["cycles"])
    value = inst["value"]  # MOVEQ sign-extends the 8-bit immediate
    ctx.push_c()
    c.i32_const(value)
    c.i32_store(offset=OFF_D + inst["reg"] * 4)
    ctx.push_c()
    c.i32_const(value)
    c.i32_const(4)
    c.call(IMP["logic_flags"])
    ctx.finish(inst["cycles"], inst["next"])


def op_rts_ram(ctx: Ctx, inst):
    c = ctx.c
    ctx.set_const(OFF_INSTR_CYCLES, inst["cycles"])
    # Guard: RAM must still contain the compiled instruction image.
    ctx.lg("pc")
    c.i32_const(0xFFFF)
    c.i32_and()
    c.i32_const(RAM_BASE)
    c.i32_add()
    ctx.ls("addr")
    c.i32_const(1)
    for offset, byte in enumerate(inst["guard"]):
        ctx.lg("addr")
        c.i32_load8_u(offset=offset)
        c.i32_const(byte)
        c.i32_eq()
        c.i32_and()
    c.if_()
    # uint32_t target = pop32(c); if (c->fault) return;
    ctx.push_c()
    c.call(IMP["pop32"])
    ctx.ls("res")
    ctx.check_fault()
    ctx.push_c()
    ctx.lg("res")
    c.i32_const(0xFFFFFF)
    c.i32_and()
    c.i32_store(offset=OFF_PC)
    c.return_()
    c.end_()
    # RAM differs from every compiled variant: same failure as the C emitter.
    ctx.fail(FAIL_RAM_VARIANT)
    c.return_()


def op_stop(ctx: Ctx, inst):
    c = ctx.c
    ctx.set_const(OFF_INSTR_CYCLES, inst["cycles"])
    ctx.load(OFF_SR)
    c.i32_const(SR_SUPERVISOR)
    c.i32_and()
    c.i32_eqz()
    c.if_()
    ctx.fail(FAIL_PRIVILEGE)
    c.return_()
    c.end_()
    ctx.push_c()
    c.i32_const(inst["sr"])
    c.call(IMP["set_sr"])
    ctx.set_const(OFF_HALTED, 1)
    ctx.finish(inst["cycles"], inst["next"])


