FAIL_BAD_PC = 2
FAIL_ODD_PC = 3
FAIL_UNMAPPED = 4
FAIL_RAM_VARIANT = 5
FAIL_PRIVILEGE = 6
FAIL_ADDRESS_ERROR = 7
FAIL_UNMAPPED_READ = 8
FAIL_UNMAPPED_WRITE = 9

# Helper ABI: what game.wasm imports from the runtime (production: runtime.wasm;
# PoC: JavaScript stubs in run_poc.mjs).  Order matters: function indices are
# assigned in this order and the JS import object uses the same names.
HELPER_IMPORTS = (
    # name, params, results
    ("read_mem", (I32, I32, I32), (I32,)),          # (c, addr, size) -> value
    ("write_mem", (I32, I32, I32, I32), ()),        # (c, addr, size, value)
    ("logic_flags", (I32, I32, I32), ()),           # (c, value, size)
    ("arithmetic", (I32, I32, I32, I32, I32, I32), (I32,)),  # (c,dst,src,size,sub,cmp)
    ("condition", (I32, I32), (I32,)),              # (c, cond) -> 0/1
    ("push32", (I32, I32), ()),                     # (c, value)
    ("pop32", (I32,), (I32,)),                      # (c) -> value
    ("set_sr", (I32, I32), ()),                     # (c, sr)
    ("fail", (I32, I32, I32), ()),                  # (c, reason, address)
)

IMP = {}  # helper name -> function index, filled by build_game_module()


# ---------------------------------------------------------------------------
# Code-emission context: tiny convenience layer over wasm_emit.Code.
# ``c`` is always parameter 0, matching the C runtime signature read_mem(c, ...).
# ---------------------------------------------------------------------------
class Ctx:
    def __init__(self, code: w.Code, params, locals_):
        self.c = code
        self._index = {}
        for i, name in enumerate(params):
            self._index[name] = i
        self._types = []
        for offset, (name, value_type) in enumerate(locals_):
            self._index[name] = len(params) + offset
            self._types.append(value_type)

    # stack/register helpers -------------------------------------------------
    def push_c(self):
        self.c.local_get(0)

    def lg(self, name):
        self.c.local_get(self._index[name])

    def ls(self, name):
        self.c.local_set(self._index[name])

    def load(self, offset):
        """Push *((uint32_t*)(c + offset))."""
        self.push_c()
        self.c.i32_load(offset=offset)

    def set_const(self, offset, value):
        self.push_c()
        self.c.i32_const(value)
        self.c.i32_store(offset=offset)

    def add_to_field(self, offset, delta):
        """*(uint32_t*)(c + offset) += delta."""
        self.push_c()
        self.load(offset)
        self.c.i32_const(delta)
        self.c.i32_add()
        self.c.i32_store(offset=offset)

    def check_fault(self):
        """if (c->fault) return;  — same guard as the C emitter."""
        self.load(OFF_FAULT)
        self.c.if_()
        self.c.return_()
        self.c.end()

    def fail(self, reason):
        """fail(c, reason, c->pc);"""
        self.push_c()
        self.c.i32_const(reason)
        self.load(OFF_PC)
        self.c.call(IMP["fail"])

    def finish(self, cycles, next_pc):
        """pc = end; return;  (cycles were already stored at handler entry)."""
        self.set_const(OFF_PC, next_pc)
        self.c.return_()


