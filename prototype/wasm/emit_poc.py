# Module assembly.
# ---------------------------------------------------------------------------
def build_game_module(with_stress=True, program=None):
    global IMP
    IMP = {}
    if program is None:
        program = PROGRAM
    module = w.Module()
    for name, params, results in HELPER_IMPORTS:
        IMP[name] = module.import_func("env", name, params, results)
    module.import_memory("env", "memory", MEMORY_PAGES)

    pages = {}
    for inst in program:
        page = inst["pc"] >> PAGE_SHIFT
        if page >= 0x100:
            continue  # RAM pages handled separately
        pages.setdefault(page, {})[slot_of(inst["pc"])] = inst
    ram_pages = {}
    for inst in program:
        page = inst["pc"] >> PAGE_SHIFT
        if page < 0x100:
            continue
        ram_pages.setdefault(page, {})[slot_of(inst["pc"])] = inst

    page_funcs = {page: module.declare_func([I32, I32], []) for page in sorted(pages)}
    ram_funcs = {
        page: module.declare_func([I32, I32], []) for page in sorted(ram_pages)
    }
    step = module.declare_func([I32], [])
    stress = module.declare_func([I32], [I32]) if with_stress else None

    for page, handlers in pages.items():
        emit_page(page_funcs[page], handlers)
    for page, handlers in ram_pages.items():
        emit_page(ram_funcs[page], handlers)
    emit_translated_step(step, page_funcs, ram_funcs)
    if stress is not None:
        emit_stress_dispatch(stress)

    module.export_func("translated_step", step.index)
    if stress is not None:
        module.export_func("stress_dispatch", stress.index)
    return module


# ---------------------------------------------------------------------------
# "Heavy" stress module: what the real backend will face — the largest Dune
# page has 1,344 translated instructions (measured from the reference C core).
# One page function therefore becomes ~300 KB of wasm code with a 32x64
# br_table dispatch and ~98 levels of block nesting.  This module lets the test
# measure that V8 accepts it and how long first-call (Liftoff) compilation takes.
# ---------------------------------------------------------------------------
HEAVY_PAGES = 3
HEAVY_SLOTS_PER_PAGE = SLOTS_PER_PAGE
HEAVY_HANDLED_PER_PAGE = 1344  # max instruction count per page in Dune USA


def _emit_heavy_filler(c: w.Code, seed: int):
    """~200 bytes of realistic handler-shaped code (memory reads, arithmetic)."""
    for step in range(20):
        c.i32_const(seed + step * 7)
        c.i32_const(0x1000)
        c.i32_load(offset=0)
        c.i32_add()
        c.drop()


def _emit_heavy_page(func: w.Func, page: int):
    c = func.code
    chunks = HEAVY_HANDLED_PER_PAGE // SLOTS_PER_CHUNK  # 21 full chunks
    for _ in range(CHUNKS_PER_PAGE + 1):
        c.block()
    c.local_get(0)
    c.i32_const(CHUNK_SHIFT)
    c.i32_shr_u()
    entries = [
        chunk if chunk < chunks else CHUNKS_PER_PAGE
        for chunk in range(CHUNKS_PER_PAGE)
    ]
    c.br_table(entries, CHUNKS_PER_PAGE)
    for chunk in range(CHUNKS_PER_PAGE):
        c.end()
        if chunk >= chunks:
            continue
        for _ in range(SLOTS_PER_CHUNK + 1):
            c.block()
        c.local_get(0)
        c.i32_const(SLOTS_PER_CHUNK - 1)
        c.i32_and()
        c.br_table(list(range(SLOTS_PER_CHUNK)), SLOTS_PER_CHUNK)
        for inner in range(SLOTS_PER_CHUNK):
            c.end()
            slot = chunk * SLOTS_PER_CHUNK + inner
            _emit_heavy_filler(c, page * 1000 + slot)
            c.i32_const(page * HEAVY_SLOTS_PER_PAGE + slot)
            c.return_()
        c.end()  # $out2
        c.i32_const(-1)
        c.return_()
    c.end()  # $out
    c.i32_const(-1)
    c.return_()


def build_heavy_module():
    """One self-contained module (own memory) with HEAVY_PAGES full-size pages."""
    module = w.Module()
    module.define_memory(1, None)
    page_funcs = {
        page: module.declare_func([I32], [I32]) for page in range(HEAVY_PAGES)
    }
    dispatch = module.declare_func([I32], [I32])
    for page in range(HEAVY_PAGES):
        _emit_heavy_page(page_funcs[page], page)
    c = dispatch.code
    for _ in range(HEAVY_PAGES + 1):
        c.block()
    c.local_get(0)
    c.i32_const(SLOTS_PER_PAGE.bit_length() - 1)  # slot >> 11 = page
    c.i32_shr_u()
    c.br_table(list(range(HEAVY_PAGES)), HEAVY_PAGES)
    for page in range(HEAVY_PAGES):
        c.end()
        c.local_get(0)
        c.i32_const(SLOTS_PER_PAGE - 1)
        c.i32_and()
        c.call(page_funcs[page].index)
        c.return_()
    c.end()
    c.i32_const(-1)
    c.return_()
    module.export_func("heavy_dispatch", dispatch.index)
    module.export_memory("memory")
    return module


def build_runtime_module():
    """Tiny stand-in for ``runtime.wasm``: owns memory + function table and
    drives ``translated_step`` through ``call_indirect`` (production wiring)."""
    module = w.Module()
    module.define_memory(MEMORY_PAGES, None)
    module.define_table(1, 1)
    step_type = module.add_type([I32], [])   # void translated_step(CPU*)
    run = module.declare_func([I32], [I32])  # run(max_steps) -> steps
    run.locals = [I32, I64, I32]             # steps, cycles, tmp
    c = run.code
    steps_local, cycles_local = 1, 2
    c.i32_const(0)
    c.local_set(steps_local)
    c.i32_const(CPU_BASE)
    c.i64_load(offset=OFF_CYCLES)            # uint64_t cycles = c->cycles
    c.local_set(cycles_local)
    c.block()
    c.loop()
    c.local_get(steps_local)
    c.local_get(0)                           # max_steps
    c.i32_ge_u()
    c.br_if(1)                               # done
    c.i32_const(CPU_BASE)                    # argument: CPU*
    c.i32_const(0)                           # table element index
    c.call_indirect(step_type)               # translated_step(c)
    # c->cycles += c->instruction_cycles;
    c.local_get(cycles_local)
    c.i32_const(CPU_BASE)
    c.i32_load(offset=OFF_INSTR_CYCLES)
    c.i64_extend_i32_u()
    c.i64_add()
    c.local_set(cycles_local)
    c.local_get(steps_local)
    c.i32_const(1)
    c.i32_add()
    c.local_set(steps_local)
    c.i32_const(CPU_BASE)
    c.i32_load(offset=OFF_FAULT)
    c.br_if(1)                               # stop on fault
    c.i32_const(CPU_BASE)
    c.i32_load(offset=OFF_HALTED)
    c.br_if(1)                               # stop on STOP
    c.br(0)
    c.end()                                  # loop
    c.end()                                  # block
    c.i32_const(CPU_BASE)
    c.local_get(cycles_local)
    c.i64_store(offset=OFF_CYCLES)
    c.local_get(steps_local)
    c.return_()
    module.export_func("run", run.index)
    module.export_memory("memory")
    module.export_table("__indirect_function_table")
    return module


def write_module(directory: Path, name: str, module: w.Module):
    data = module.build()
    path = directory / name
    path.write_bytes(data)
    return data, path


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        default=str(Path(__file__).resolve().parent / "build"),
        help="output directory (default: ./build next to this script)",
    )
    args = parser.parse_args(argv)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    started = time.perf_counter()
    game_module = build_game_module(with_stress=True)
    game_bytes, game_path = write_module(out, "poc.wasm", game_module)
    # Same module without the 2048-slot stress dispatcher: used to report the
    # marginal code size of the translated handlers (docs/WASM-BACKEND.md §12).
    min_bytes = len(build_game_module(with_stress=False).build())
    # ...and with no translated instructions at all, to separate dispatch/ABI
    # overhead from the marginal cost of one handler.
    skeleton_bytes = len(build_game_module(with_stress=False, program=[]).build())
    runtime_module = build_runtime_module()
    runtime_bytes, runtime_path = write_module(out, "poc-runtime.wasm", runtime_module)
    heavy_module = build_heavy_module()
    heavy_bytes, heavy_path = write_module(out, "poc-heavy.wasm", heavy_module)
    abi_a_bytes, abi_a_path = write_module(out, "poc-abi-a.wasm", build_abi_module_a())
    abi_b_bytes, abi_b_path = write_module(out, "poc-abi-b.wasm", build_abi_module_b())
    elapsed_ms = (time.perf_counter() - started) * 1000.0

    page_handlers = {}
    for inst in PROGRAM:
        page = inst["pc"] >> PAGE_SHIFT
        key = "ram" if page >= 0x100 else "rom"
        page_handlers.setdefault(key, set()).add(page)

    meta = {
        "format": "dune-wasm-backend-poc/1",
        "abi_version": 1,
        "abi": {
            "cpu_base": CPU_BASE,
            "memory_pages": MEMORY_PAGES,
            "offsets": {
                "d": OFF_D,
                "a": OFF_A,
                "pc": OFF_PC,
                "sr": OFF_SR,
                "fault": OFF_FAULT,
                "fault_code": OFF_FAULT_CODE,
                "cycles": OFF_CYCLES,
                "halted": OFF_HALTED,
                "instruction_cycles": OFF_INSTR_CYCLES,
            },
            "ram_base": RAM_BASE,
            "ram_bytes": RAM_BYTES,
            "helpers": [name for name, _, _ in HELPER_IMPORTS],
            "fail_codes": {
                "untranslated": FAIL_UNTRANSLATED,
                "bad_pc": FAIL_BAD_PC,
                "odd_pc": FAIL_ODD_PC,
                "unmapped": FAIL_UNMAPPED,
                "ram_variant": FAIL_RAM_VARIANT,
                "privilege": FAIL_PRIVILEGE,
            },
        },
        "dispatch": {
            "page_shift": PAGE_SHIFT,
            "slots_per_page": SLOTS_PER_PAGE,
            "slots_per_chunk": SLOTS_PER_CHUNK,
            "chunks_per_page": CHUNKS_PER_PAGE,
            "page_group_shift": 4,
            "ram_pages": [0xFF0 + index for index in range(RAM_PAGE_COUNT)],
        },
        "program": [
            {
                "pc": inst["pc"],
                "op": inst["op"],
                "cycles": inst["cycles"],
                "page": inst["pc"] >> PAGE_SHIFT,
            }
            for inst in PROGRAM
        ],
        "modules": {
            "game_bytes_without_stress": min_bytes,
            "game_bytes_no_handlers": skeleton_bytes,
            "game_bytes": len(game_bytes),
            "game_sha256": hashlib.sha256(game_bytes).hexdigest(),
            "runtime_bytes": len(runtime_bytes),
            "runtime_sha256": hashlib.sha256(runtime_bytes).hexdigest(),
            "heavy_bytes": len(heavy_bytes),
            "heavy_sha256": hashlib.sha256(heavy_bytes).hexdigest(),
            "abi_a_bytes": len(abi_a_bytes),
            "abi_b_bytes": len(abi_b_bytes),
        },
        "abi_bench": {
            "callee": ABI_BENCH_CALLEE,
            "modes": ["local", "import", "js", "table"],
            "note": "measure ns/call in run_poc.mjs; V8/Node numbers, phone scales",
        },
        "heavy": {
            "pages": HEAVY_PAGES,
            "slots_per_page": HEAVY_SLOTS_PER_PAGE,
            "handled_per_page": HEAVY_HANDLED_PER_PAGE,
        },
        "generation_ms": round(elapsed_ms, 2),
    }
    meta_path = out / "poc-meta.json"
    meta_path.write_text(json.dumps(meta, indent=2) + "\n")

    print("emitted %s (%d bytes, sha256 %s)" % (game_path, len(game_bytes),
                                                meta["modules"]["game_sha256"][:16]))
    print("emitted %s (%d bytes, sha256 %s)" % (runtime_path, len(runtime_bytes),
                                                meta["modules"]["runtime_sha256"][:16]))
    print("emitted %s (%d bytes, sha256 %s)" % (heavy_path, len(heavy_bytes),
                                                meta["modules"]["heavy_sha256"][:16]))
    print("emitted %s (%d bytes) and %s (%d bytes)" % (abi_a_path, len(abi_a_bytes),
                                                       abi_b_path, len(abi_b_bytes)))
    print("emitted %s" % meta_path)
    print("pages: rom=%d ram=%d instructions=%d generation=%.2f ms" % (
        len(page_handlers.get("rom", ())), len(page_handlers.get("ram", ())),
        len(PROGRAM), elapsed_ms))
    return 0


if __name__ == "__main__":
    sys.exit(main())
