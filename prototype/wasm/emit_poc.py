"""PoC of the on-device WASM backend: synthetic translated program -> game.wasm.

This is a small but honest slice of ``docs/WASM-BACKEND.md``.  It does what the
future Python emitter will do for the real 68000/Z80 translation, but for a
hand-written synthetic program:

    * CPU/register file lives in *linear memory* (owned by the runtime in the
      real split; in this PoC the memory is imported from the host);
    * memory reads/writes go through imported runtime helpers (``read_mem`` /
      ``write_mem``), exactly like the C emitter calls them;
    * instructions are grouped into 4 KiB pages; ``translated_step`` dispatches
      ``pc -> page`` with a two-level ``br_table`` (16 groups x 16 pages) and
      each page dispatches ``pc -> instruction`` with a second two-level
      ``br_table`` (32 chunks x 64 slots), the handler body inlined between the
      blocks.  No interpreter, no fetch/decode at runtime;
    * ROM pages (0x000000..0x0FFFFF) and RAM pages (0xFF0000..0xFFFFFF) use
      separate dispatch regions; a RAM handler first guards its bytes against
      the compiled image (self-modifying code / Z80 variants in the real code);
    * the module has no data segments: ROM bytes stay in the runtime, RAM is
      read through the ABI base address (``RAM_BASE`` here; the real emitter
      takes the address from the runtime ABI descriptor);
    * a second, tiny ``poc-runtime.wasm`` (generated by the same encoder) proves
      the module-to-module wiring: it owns the memory and the function table and
      calls ``translated_step`` through ``call_indirect`` — the production
      direction of the call.

Run ``run_poc.mjs`` to instantiate and verify the result.

Python 3.9+ compatible.  Usage:

    python3 emit_poc.py [--out DIR]
"""

