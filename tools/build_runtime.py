def compare_artifacts(manifest, runtime_bytes, adapters_m) -> list:
    """Return human-readable differences between on-disk and freshly built pins."""
    problems = []
    runtime_path = RUNTIME_DIR / RUNTIME_FILE
    if not runtime_path.is_file():
        problems.append(f"missing runtime file: {runtime_path}")
    elif runtime_path.read_bytes() != runtime_bytes:
        problems.append(
            f"{RUNTIME_FILE} differs: on disk {sha256_file(runtime_path)}, expected {manifest['runtime_sha256']}"
        )
    sidecar = RUNTIME_DIR / (RUNTIME_FILE + ".sha256")
    expected_sidecar = f"{manifest['runtime_sha256']}  {RUNTIME_FILE}\n"
    if not sidecar.is_file():
        problems.append(f"missing SHA-256 sidecar: {sidecar}")
    elif sidecar.read_text(encoding="utf-8") != expected_sidecar:
        problems.append(f"{sidecar.name} content differs")
    manifest_path = RUNTIME_DIR / "manifest.json"
    if not manifest_path.is_file():
        problems.append(f"missing manifest: {manifest_path}")
    else:
        on_disk = json.loads(manifest_path.read_text(encoding="utf-8"))
        if on_disk != manifest:
            keys = sorted(
                key
                for key in set(on_disk) | set(manifest)
                if on_disk.get(key) != manifest.get(key)
            )
            problems.append("runtime/manifest.json differs in: " + ", ".join(keys))
    adapters_path = ADAPTERS_DIR / ADAPTERS_MANIFEST
    if not adapters_path.is_file():
        problems.append(f"missing adapters manifest: {adapters_path}")
    else:
        on_disk = json.loads(adapters_path.read_text(encoding="utf-8"))
        if on_disk != adapters_m:
            problems.append(f"runtime/adapters/{ADAPTERS_MANIFEST} differs")
    local_core = ROOT / ".local/build/dune-web.c"
    if local_core.is_file() and sha256_file(local_core) != manifest["shipped_core_sha256"]:
        problems.append(".local/build/dune-web.c does not match the pinned shipped core")
    return problems


def write_artifacts(manifest, runtime_bytes, adapters_m) -> None:
    RUNTIME_DIR.mkdir(parents=True, exist_ok=True)
    (RUNTIME_DIR / RUNTIME_FILE).write_bytes(runtime_bytes)
    (RUNTIME_DIR / (RUNTIME_FILE + ".sha256")).write_text(
        f"{manifest['runtime_sha256']}  {RUNTIME_FILE}\n", encoding="utf-8"
    )
    (RUNTIME_DIR / "manifest.json").write_bytes(_json_bytes(manifest))
    ADAPTERS_DIR.mkdir(parents=True, exist_ok=True)
    (ADAPTERS_DIR / ADAPTERS_MANIFEST).write_bytes(_json_bytes(adapters_m))


def run(baseline, adapters_from=None, check_only=False) -> dict:
    started = time.perf_counter()
    timings = {}

    step = time.perf_counter()
    baseline_info = bootstrap.verify_baseline(Path(baseline))
    timings["baseline"] = time.perf_counter() - step

    step = time.perf_counter()
    adapters = sync_adapters(adapters_from)
    adapters_m = adapters_manifest(adapters)
    timings["adapters"] = time.perf_counter() - step

    if not check_only:
        step = time.perf_counter()
        bootstrap.prepare_local(baseline=Path(baseline))
        timings["bootstrap"] = time.perf_counter() - step

    step = time.perf_counter()
    recompiler_dir = ROOT / ".local/source/genesis_recompiler"
    if not (recompiler_dir / "audio_ymfm.cpp").is_file():
        recompiler_dir = bootstrap.VENDOR / "genesis_recompiler"
    base_text = Path(baseline).read_text(encoding="utf-8")
    prepared = prepare_source.apply(base_text, ADAPTERS_DIR, recompiler_dir)
    timings["prepare"] = time.perf_counter() - step

    step = time.perf_counter()
    preamble = extract_preamble(prepared["core"])
    manifest = build_manifest(adapters, preamble)
    timings["extract"] = time.perf_counter() - step

    if check_only:
        problems = compare_artifacts(manifest, preamble["runtime_bytes"], adapters_m)
        return {
            "mode": "check",
            "ok": not problems,
            "problems": problems,
            "runtime_file": manifest["runtime_file"],
            "runtime_sha256": manifest["runtime_sha256"],
            "runtime_bytes": manifest["runtime_bytes"],
            "adapters": manifest["adapters"]["count"],
            "baseline_sha256": baseline_info["sha256"],
            "shipped_core_sha256": prepared["core_sha256"],
            "shipped_core_bytes": prepared["core_bytes"],
            "timings": timings,
            "total_seconds": time.perf_counter() - started,
        }

    step = time.perf_counter()
    write_artifacts(manifest, preamble["runtime_bytes"], adapters_m)
    prepare_source.write_outputs(
        prepared, ROOT / ".local/build/dune-web.c", ROOT / ".local/build/dune-web-audio.cpp"
    )
    (ROOT / ".local/build/prepare-report.json").write_bytes(
        _json_bytes(
            {
                "baseline_sha256": baseline_info["sha256"],
                "baseline_bytes": baseline_info["bytes"],
                "core_sha256": prepared["core_sha256"],
                "core_bytes": prepared["core_bytes"],
                "audio_sha256": prepared["audio_sha256"],
                "audio_bytes": prepared["audio_bytes"],
                "preamble_sha256": preamble["full_preamble_sha256"],
                "runtime_sha256": preamble["runtime_sha256"],
                "translated_section_unchanged": prepared["translated_section_unchanged"],
            }
        )
    )
    timings["write"] = time.perf_counter() - step

    return {
        "mode": "build",
        "ok": True,
        "runtime_file": manifest["runtime_file"],
        "runtime_sha256": manifest["runtime_sha256"],
        "runtime_bytes": manifest["runtime_bytes"],
        "full_preamble_sha256": manifest["full_preamble_sha256"],
        "full_preamble_bytes": manifest["full_preamble_bytes"],
        "shipped_core_sha256": prepared["core_sha256"],
        "shipped_core_bytes": prepared["core_bytes"],
        "shipped_audio_sha256": prepared["audio_sha256"],
        "shipped_audio_bytes": prepared["audio_bytes"],
        "adapters": manifest["adapters"]["count"],
        "adapters_bytes": manifest["adapters"]["bytes"],
        "baseline_sha256": baseline_info["sha256"],
        "timings": timings,
        "total_seconds": time.perf_counter() - started,
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--baseline",
        type=Path,
        required=True,
        help="external vendor/rearrakis/build/dune-base.c (20 412 009 bytes, SHA-256 e3055a76...)",
    )
    parser.add_argument(
        "--adapters-from",
        type=Path,
        help="optional directory with the previous port's MIT em_web_*.h adapters (sync into runtime/adapters)",
    )
    parser.add_argument("--check", action="store_true", help="recompute in memory and compare; write nothing")
    parser.add_argument("--json", action="store_true", help="print a JSON report")
    args = parser.parse_args(argv)
    try:
        report = run(args.baseline, args.adapters_from, args.check)
    except (ValueError, FileNotFoundError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        prefix = "check" if report["mode"] == "check" else "build"
        print(f"runtime v2 {prefix}: {report['runtime_sha256']} ({report['runtime_bytes']} bytes)")
        print("shipped core: " + report["shipped_core_sha256"] + f" ({report['shipped_core_bytes']} bytes)")
        print(f"adapters: {report['adapters']} files")
        print(f"baseline: {report['baseline_sha256']}")
        if report["mode"] == "check":
            if report["ok"]:
                print("committed runtime artifacts match a fresh build")
            else:
                for problem in report["problems"]:
                    print(f"error: {problem}", file=sys.stderr)
        else:
            print(f"wrote runtime/{RUNTIME_FILE}, runtime/{RUNTIME_FILE}.sha256, runtime/manifest.json")
            print("local prepared core: .local/build/dune-web.c (not committed)")
        print(f"elapsed: {report['total_seconds']:.2f}s")
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
