#!/usr/bin/env python3
"""Build the pinned v2 runtime preamble from the external generated baseline.

The runtime is the *code* part of the generated core: MC68000/Z80 scheduling, VDP
and audio, SDL host, browser host/input adapters and ``DSAV`` v2 save state. It
contains no ROM bytes and no translated game instructions. The generated core is

    <emitter header>            (3 lines: comment + GENESIS_DUNE_MOUSE + title)
    runtime/../dune-runtime-v2.c  <- this tool extracts exactly these bytes
    static const uint8_t rom_data[] = {...};  <- ROM data, player-supplied
    translated 68000/Z80 code   <- player-supplied

``runtime/dune-runtime-v2.c`` is therefore the exact text that the recompiler
receives through ``--pinned-runtime``; ``tools/build_game_c.py`` reproduces the
prepared core byte-for-byte from a player ROM.

Inputs (never stored in this repository):
  --baseline PATH   external ``vendor/rearrakis/build/dune-base.c`` (20 412 009
                    bytes, SHA-256 e3055a76...), i.e. the pinned generated source.
  --adapters-from   optional source directory with our 20 MIT ``em_web_*.h``
                    adapters (the previous port's ``tools/`` directory). Usually
                    the adapters are already committed under ``runtime/adapters``.

Usage:
    python3 tools/build_runtime.py --baseline /path/to/vendor/rearrakis/build/dune-base.c
    python3 tools/build_runtime.py --baseline ... --check   # verify, write nothing

Outputs: ``runtime/dune-runtime-v2.c``, ``runtime/dune-runtime-v2.c.sha256``,
``runtime/manifest.json``, ``runtime/adapters/manifest.json`` and local build
artifacts in ``.local/build/`` (game data, untracked).
"""
