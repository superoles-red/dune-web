EXPORT_RE = re.compile(r"EMSCRIPTEN_KEEPALIVE[^;{}#\n]*?\b([A-Za-z_]\w*)\s*\(")
BYTE_RUN_RE = re.compile(r"(?:0x[0-9a-fA-F]{2}\s*,\s*){16,}")
ADAPTER_INCLUDE_RE = re.compile(r'#include\s+"(em_web_[A-Za-z0-9_]+\.h)"')


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256(path.read_bytes())


def _json_bytes(value) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def sync_adapters(source=None):
    """Verify/import the pinned MIT adapters and return their manifest entries."""
    if source is not None:
        source = Path(source)
        if not source.is_dir():
            raise FileNotFoundError(f"adapter source directory not found: {source}")
        ADAPTERS_DIR.mkdir(parents=True, exist_ok=True)
        for name in sorted(EXPECTED_ADAPTERS):
            candidate = source / name
            if not candidate.is_file():
                raise FileNotFoundError(f"adapter missing in source: {candidate}")
            data = candidate.read_bytes()
            if sha256(data) != ADAPTER_SHA256[name]:
                raise ValueError(
                    f"adapter {name} does not match the pinned MIT adapter identity"
                )
            target = ADAPTERS_DIR / name
            if not target.is_file() or target.read_bytes() != data:
                target.write_bytes(data)
    if not ADAPTERS_DIR.is_dir():
        raise FileNotFoundError(
            f"adapters not found: {ADAPTERS_DIR}; pass --adapters-from <previous tools/ dir>"
        )
    present = {path.name for path in ADAPTERS_DIR.glob("em_web_*.h")}
    missing = sorted(EXPECTED_ADAPTERS - present)
    unexpected = sorted(present - EXPECTED_ADAPTERS)
    if missing or unexpected:
        raise ValueError(
            "adapter set mismatch: missing " + str(missing) + ", unexpected " + str(unexpected)
        )
    entries = []
    for name in sorted(EXPECTED_ADAPTERS):
        data = (ADAPTERS_DIR / name).read_bytes()
        if sha256(data) != ADAPTER_SHA256[name]:
            raise ValueError(f"adapter changed since it was pinned: {name}")
        entries.append({"name": name, "bytes": len(data), "sha256": sha256(data)})
    return entries


def adapters_manifest(entries) -> dict:
    return {
        "format": 1,
        "license": "MIT",
        "description": (
            "Browser host/input adapters of this port. Code only: no ROM bytes, no "
            "translated game instructions. Included by the pinned runtime preamble."
        ),
        "count": len(entries),
        "bytes": sum(entry["bytes"] for entry in entries),
        "files": entries,
    }


def extract_preamble(prepared: str) -> dict:
    """Split the prepared core into emitter header, runtime body and game part."""
    if prepared.count(MARKER) != 1:
        raise ValueError("prepared core must contain exactly one rom_data marker")
    index = prepared.index(MARKER)
    preamble = prepared[:index]
    if not preamble.startswith(GENERATED_PREFIX):
        raise ValueError("prepared core preamble does not start with the emitter header")
    runtime = preamble[len(GENERATED_PREFIX):]
    if not runtime.endswith("\n"):
        raise ValueError("runtime body must end with a newline")
    runtime = runtime[:-1]
    if not runtime.endswith("\n"):
        raise ValueError("runtime body is missing its final newline")
    if GENERATED_PREFIX + runtime + "\n" != preamble:
        raise ValueError("runtime body does not recompose the full preamble")
    validate_runtime_text(runtime)
    return {
        "runtime": runtime,
        "runtime_bytes": runtime.encode("utf-8"),
        "runtime_sha256": sha256(runtime.encode("utf-8")),
        "full_preamble": preamble,
        "full_preamble_bytes": len(preamble.encode("utf-8")),
        "full_preamble_sha256": sha256(preamble.encode("utf-8")),
        "generated_prefix": GENERATED_PREFIX,
        "generated_prefix_bytes": len(GENERATED_PREFIX.encode("utf-8")),
        "generated_prefix_sha256": sha256(GENERATED_PREFIX.encode("utf-8")),
        "game_part": prepared[index:],
    }


def validate_runtime_text(runtime: str) -> None:
    """Fail closed if the extracted preamble could contain game data."""
    encoded = runtime.encode("utf-8")
    if len(encoded) > MAX_RUNTIME_BYTES:
        raise ValueError(f"runtime is too large to be a code-only preamble: {len(encoded)} bytes")
    if len(encoded) < 50 * 1024:
        raise ValueError(f"runtime is suspiciously small: {len(encoded)} bytes")
    if MARKER in runtime or "static const uint8_t rom_data[]" in runtime:
        raise ValueError("runtime contains the ROM data marker")
    match = BYTE_RUN_RE.search(runtime)
    if match:
        raise ValueError(
            "runtime contains a long byte-array run that looks like embedded ROM data: "
            + match.group(0)[:60]
        )
    if "#define DUNE_SAVESTATE_VERSION 2" not in runtime:
        raise ValueError("runtime does not carry the DSAV v2 save ABI")
    if "#define DUNE_SAVESTATE_VERSION 1" in runtime:
        raise ValueError("runtime still carries the DSAV v1 save ABI")
    includes = ADAPTER_INCLUDE_RE.findall(runtime)
    if not includes:
        raise ValueError("runtime does not include the browser adapters")
    unknown = sorted(set(includes) - EXPECTED_ADAPTERS)
    if unknown:
        raise ValueError("runtime includes unknown adapters: " + str(unknown))


def extract_exports(runtime: str):
    names = sorted(set(EXPORT_RE.findall(runtime)))
    return names


def adapter_exports(entries):
    names = set()
    for entry in entries:
        text = (ADAPTERS_DIR / entry["name"]).read_text(encoding="utf-8")
        names.update(EXPORT_RE.findall(text))
    return sorted(names)


