def compile_runtime(runner: CommandRunner, build_dir: Path, runtime_manifest: dict) -> None:
    obj_dir = build_dir / "obj"
    obj_dir.mkdir(parents=True, exist_ok=True)
    runtime_c = write_runtime_c(build_dir)

    common_includes = [
        f"-I{ROOT / 'runtime' / 'adapters'}",
        f"-I{ROOT / 'vendor' / 'rearrakis' / 'genesis_recompiler'}",
        f"-I{SRC_DIR}",
        f"-I{build_dir}",
    ]

    runner.run(
        "compile-runtime",
        [
            "emcc",
            "-O2",
            "-std=c11",
            "-Wno-unused-function",
            "-DGENESIS_SDL2",
            "-DGENESIS_AUDIO",
            "-D__EMSCRIPTEN__",
            "-sUSE_SDL=2",
            *common_includes,
            "-c",
            str(runtime_c),
            "-o",
            str(obj_dir / "runtime.o"),
        ],
    )
    runner.run(
        "compile-audio",
        [
            "em++",
            "-O2",
            "-std=c++17",
            f"-I{ROOT / 'vendor' / 'rearrakis' / 'genesis_recompiler'}",
            "-c",
            str(build_dir / "audio_patched.cpp"),
            "-o",
            str(obj_dir / "audio.o"),
        ],
    )
    runner.run(
        "link-runtime",
        [
            "em++",
            "-O2",
            "-sUSE_SDL=2",
            "-sSTANDALONE_WASM=1",
            "--no-entry",
            "-sIMPORTED_MEMORY=1",
            f"-sINITIAL_MEMORY={INITIAL_MEMORY_BYTES}",
            f"-sMAXIMUM_MEMORY={MAXIMUM_MEMORY_BYTES}",
            "-sALLOW_MEMORY_GROWTH=1",
            "-sALLOW_TABLE_GROWTH=1",
            f"-sSTACK_SIZE={STACK_BYTES}",
            str(obj_dir / "runtime.o"),
            str(obj_dir / "audio.o"),
            "-o",
            str(build_dir / "runtime.wasm"),
        ],
    )


def build_stub_game(runner: CommandRunner, build_dir: Path, emsdk: Path) -> None:
    clang = emsdk / "upstream" / "bin" / "clang"
    wasm_ld = emsdk / "upstream" / "bin" / "wasm-ld"
    if not clang.is_file() or not wasm_ld.is_file():
        raise BuildError(f"emsdk upstream clang/wasm-ld missing under {emsdk}")
    obj = build_dir / "obj" / "stub_game.o"
    runner.run(
        "compile-stub-game",
        [
            str(clang),
            "--target=wasm32",
            "-O2",
            "-nostdlib",
            "-ffreestanding",
            "-fno-builtin",
            "-I",
            str(build_dir),
            "-c",
            str(SRC_DIR / "stub_game.c"),
            "-o",
            str(obj),
        ],
    )
    runner.run(
        "link-stub-game",
        [
            str(wasm_ld),
            "--no-entry",
            "--import-memory",
            "--allow-undefined",
            f"--global-base={STUB_GLOBAL_BASE}",
            *[f"--export={name}" for name in STUB_EXPORTS],
            "-o",
            str(build_dir / "stub_game.wasm"),
            str(obj),
        ],
    )


def validate_runtime_wasm(info: dict, runtime_manifest: dict) -> dict:
    if info["bytes"] > MAX_RUNTIME_WASM_BYTES:
        raise BuildError(
            f"runtime.wasm is {info['bytes']} bytes (> {MAX_RUNTIME_WASM_BYTES}); game data may have leaked"
        )
    if info["data_bytes"] > MAX_DATA_SEGMENT_BYTES:
        raise BuildError(
            f"runtime.wasm has {info['data_bytes']} data-segment bytes; expected < {MAX_DATA_SEGMENT_BYTES}"
        )
    largest = max(info["data_segment_sizes"], default=0)
    if largest >= MAX_SINGLE_DATA_SEGMENT_BYTES:
        raise BuildError(
            f"runtime.wasm has a {largest}-byte data segment; that smells like embedded game data"
        )
    if info["memory_section"]:
        raise BuildError("runtime.wasm defines its own memory; it must import the JS-owned memory")

    import_names = [(item["module"], item["name"], item["kind"]) for item in info["imports"]]
    if ("env", "memory", "memory") not in import_names:
        raise BuildError("runtime.wasm does not import env.memory")
    export_map = {item["name"]: item["kind"] for item in info["exports"]}
    if export_map.get("__indirect_function_table") != "table":
        raise BuildError("runtime.wasm does not export __indirect_function_table")
    if export_map.get("_initialize") != "function":
        raise BuildError("runtime.wasm does not export _initialize (reactor init)")

    missing: list[str] = []
    must_export = set(ABI_EXPORTS)
    must_export.update(runtime_manifest["exports"]["runtime"])
    must_export.update(runtime_manifest["exports"]["adapters"])
    must_export.update(runtime_manifest["exports"]["save"])
    must_export.update(["run_main", "sdl_host_service"])
    for name in sorted(must_export):
        if export_map.get(name) != "function":
            missing.append(name)
    if missing:
        raise BuildError(f"runtime.wasm is missing exports: {', '.join(missing)}")

    env_imports = sorted({
        item["name"] for item in info["imports"]
        if item["module"] == "env" and item["kind"] == "function"
    })
    wasi_imports = sorted({item["name"] for item in info["imports"] if item["module"] == "wasi_snapshot_preview1"})
    return {
        "env_imports": env_imports,
        "wasi_imports": wasi_imports,
        "export_names": sorted(export_map),
    }


def validate_stub_wasm(path: Path) -> dict:
    info = parse_wasm(path)
    if info["bytes"] > 64 * 1024:
        raise BuildError("stub_game.wasm is unexpectedly large")
    if info["data_bytes"] != 0:
        raise BuildError(f"stub_game.wasm has {info['data_bytes']} data-segment bytes; it must be code-only")
    import_names = {(item["module"], item["name"], item["kind"]) for item in info["imports"]}
    expected_imports = {
        ("env", "memory", "memory"),
        ("env", "dune_write_mem", "function"),
        ("env", "dune_read_mem", "function"),
    }
    if not expected_imports.issubset(import_names):
        raise BuildError(f"stub_game.wasm imports unexpected set: {sorted(import_names)}")
    export_names = {item["name"] for item in info["exports"]}
    missing = set(STUB_EXPORTS) - export_names
    if missing:
        raise BuildError(f"stub_game.wasm is missing exports: {sorted(missing)}")
    return info


