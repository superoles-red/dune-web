def determinism_check(runner: CommandRunner, build_dir: Path, out_wasm: Path) -> dict:
    first = out_wasm.read_bytes()
    first_sha = sha256_bytes(first)
    (build_dir / "runtime.determinism-1.wasm").write_bytes(first)
    obj_dir = build_dir / "obj"
    runner.run(
        "link-runtime-repeat",
        [
            "em++",
            "-O2",
            "-sUSE_SDL=2",
            "-sSTANDALONE_WASM=1",
            "--no-entry",
            "-sIMPORTED_MEMORY=1",
            f"-sINITIAL_MEMORY={INITIAL_MEMORY_BYTES}",
            f"-sMAXIMUM_MEMORY={MAXIMUM_MEMORY_BYTES}",
            "-sALLOW_MEMORY_GROWTH=1",
            "-sALLOW_TABLE_GROWTH=1",
            f"-sSTACK_SIZE={STACK_BYTES}",
            str(obj_dir / "runtime.o"),
            str(obj_dir / "audio.o"),
            "-o",
            str(build_dir / "runtime.determinism-2.wasm"),
        ],
    )
    second = (build_dir / "runtime.determinism-2.wasm").read_bytes()
    second_sha = sha256_bytes(second)
    return {
        "deterministic": first_sha == second_sha,
        "first_sha256": first_sha,
        "second_sha256": second_sha,
        "note": (
            "Two consecutive wasm-ld links from identical objects."
            if first_sha == second_sha
            else "Link output is not byte-identical; documented as non-deterministic."
        ),
    }


