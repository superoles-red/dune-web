def render_loader(build_dir: Path) -> tuple[Path, str]:
    template = (SRC_DIR / "loader.mjs.tmpl").read_text(encoding="utf-8")
    fields = "[" + ", ".join(json.dumps(name) for name in abi_spec.FIELD_NAMES) + "]"
    meta = json.dumps(loader_meta(), indent=2)
    if template.count("__ABI_FIELDS_JSON__") != 1 or template.count("__ABI_META_JSON__") != 1:
        raise BuildError("loader.mjs template placeholders changed")
    loader = template.replace("__ABI_FIELDS_JSON__", fields).replace("__ABI_META_JSON__", meta)
    path = build_dir / "loader.mjs"
    path.write_text(loader, encoding="utf-8")
    return path, sha256_bytes(loader.encode("utf-8"))


DUMP_ABI_SCRIPT = r"""
import { readFile } from 'node:fs/promises';
import { loadRuntime, initRuntime, verifyAbiHash, abiHashHex, ABI, ABI_FIELDS } from './loader.mjs';

const wasmPath = process.argv[2];
const bytes = await readFile(wasmPath);
const rt = await loadRuntime({ wasmBytes: bytes });
const romBeforeInit = rt.exports.dune_rt_rom_buffer();
const initializedBefore = rt.exports.dune_rt_initialized();
initRuntime(rt);
const romAfterInit = rt.exports.dune_rt_rom_buffer();
const romCapacity = rt.exports.dune_rt_rom_capacity();
const cpuPtr = rt.exports.dune_cpu_ptr();
const saveBuffer = rt.exports.dune_get_save_buffer();
const saveCapacity = rt.exports.dune_rt_save_buffer_capacity();
const wordCount = rt.exports.dune_abi_word_count();
const abiVersion = rt.exports.dune_abi_version();
const helperVersion = rt.exports.dune_abi_helper_version();
const hashPointer = rt.exports.dune_abi_hash();
const selfcheck = rt.exports.dune_abi_selfcheck(ABI.version, hashPointer);
const hashOk = await verifyAbiHash(rt.abi);
const hashHex = await abiHashHex(rt.abi);
rt.exports.dune_rt_init();
const romAfterSecondInit = rt.exports.dune_rt_rom_buffer();
const failCodeCount = Object.keys(ABI.failCodes).length;
const fields = Object.fromEntries(ABI_FIELDS.map((name) => [name, rt.abi.fields[name]]));
console.log(JSON.stringify({
  ok: true,
  word_count_export: wordCount,
  abi_version_export: abiVersion,
  helper_version_export: helperVersion,
  selfcheck,
  hash_ok: hashOk,
  hash_hex: hashHex,
  rom_before_init: romBeforeInit,
  initialized_before_init: initializedBefore,
  rom_after_init: romAfterInit,
  rom_after_second_init: romAfterSecondInit,
  rom_capacity: romCapacity,
  cpu_ptr: cpuPtr,
  save_buffer: saveBuffer,
  save_capacity: saveCapacity,
  fail_code_count: failCodeCount,
  fields,
}));
"""


def dump_abi(runner: CommandRunner, build_dir: Path, runtime_wasm: Path, node: str) -> dict:
    script = build_dir / "dump_abi.mjs"
    script.write_text(DUMP_ABI_SCRIPT, encoding="utf-8")
    result = runner.run(
        "dump-abi",
        [node, str(script), str(runtime_wasm)],
        timeout=600,
    )
    lines = [line for line in result.stdout.splitlines() if line.strip()]
    payload = None
    for line in reversed(lines):
        line = line.strip()
        if line.startswith("{") and line.endswith("}"):
            try:
                payload = json.loads(line)
                break
            except json.JSONDecodeError:
                continue
    if payload is None:
        raise BuildError(f"node ABI dump produced no JSON; stdout:\n{result.stdout}\n{result.stderr}")
    return payload


def validate_abi_dump(payload: dict) -> None:
    if payload.get("ok") is not True:
        raise BuildError("ABI dump not ok")
    if payload["word_count_export"] != abi_spec.WORD_COUNT:
        raise BuildError("descriptor word count export mismatch")
    if payload["abi_version_export"] != abi_spec.ABI_VERSION:
        raise BuildError("descriptor version export mismatch")
    if payload["helper_version_export"] != abi_spec.HELPER_ABI_VERSION:
        raise BuildError("helper ABI version export mismatch")
    if payload["selfcheck"] != 1:
        raise BuildError("dune_abi_selfcheck() failed")
    if payload["hash_ok"] is not True:
        raise BuildError("descriptor abi_hash does not match its structural words")
    if payload["initialized_before_init"] != 0:
        raise BuildError("runtime reports initialized before dune_rt_init()")
    if payload["rom_before_init"] != 0:
        raise BuildError("ROM buffer exists before dune_rt_init(); it must be allocated at runtime")
    if payload["rom_after_init"] == 0:
        raise BuildError("dune_rt_init() did not allocate the ROM buffer")
    if payload["rom_after_init"] != payload["rom_after_second_init"]:
        raise BuildError("dune_rt_init() is not idempotent (ROM buffer moved)")
    if payload["rom_capacity"] != abi_spec.ROM_CAPACITY:
        raise BuildError("ROM buffer capacity mismatch")
    if payload["save_capacity"] != abi_spec.SAVE_BUFFER_BYTES:
        raise BuildError("save buffer capacity mismatch")
    if payload["fail_code_count"] != len(abi_spec.FAIL_CODES):
        raise BuildError("fail code count mismatch")
    fields = payload["fields"]
    for name, expected in abi_spec.CONSTANTS.items():
        actual = fields[name]
        if actual != expected:
            raise BuildError(f"ABI constant {name} = {actual}, expected {expected}")
    for name in abi_spec.ADDRESS_FIELDS:
        if not fields[name]:
            raise BuildError(f"ABI address {name} is null after dune_rt_init()")
    for name in ("SIZEOF_CPU", "SIZEOF_Z80CPU", "OFF_RAM", "OFF_Z80_RAM", "OFF_VDP_FRAME"):
        if not fields[name]:
            raise BuildError(f"ABI field {name} is zero")


