def read_uleb(data: bytes, offset: int) -> tuple[int, int]:
    result = 0
    shift = 0
    while True:
        byte = data[offset]
        offset += 1
        result |= (byte & 0x7F) << shift
        if not byte & 0x80:
            return result, offset
        shift += 7


def skip_limits(data: bytes, offset: int) -> int:
    flags = data[offset]
    offset += 1
    _minimum, offset = read_uleb(data, offset)
    if flags & 1:
        _maximum, offset = read_uleb(data, offset)
    return offset


def skip_init_expr(data: bytes, offset: int) -> int:
    while True:
        opcode = data[offset]
        offset += 1
        if opcode == 0x0B:  # end
            return offset
        if opcode in (0x41, 0x42):  # i32.const / i64.const
            while data[offset] & 0x80:
                offset += 1
            offset += 1
        elif opcode == 0x23:  # global.get
            _index, offset = read_uleb(data, offset)
        else:
            raise BuildError(f"unexpected opcode in init expr: 0x{opcode:02x}")


def parse_wasm(path: Path) -> dict:
    data = path.read_bytes()
    if data[:4] != b"\x00asm" or data[4:8] != b"\x01\x00\x00\x00":
        raise BuildError(f"{path} is not a wasm binary")
    offset = 8
    imports: list[dict] = []
    exports: list[dict] = []
    sections: list[dict] = []
    data_bytes = 0
    data_segments = 0
    data_segment_sizes: list[int] = []
    memory_section = False
    while offset < len(data):
        section_id = data[offset]
        offset += 1
        size, offset = read_uleb(data, offset)
        body_start = offset
        body_end = offset + size
        sections.append({"id": section_id, "bytes": size})
        if section_id == 2:  # imports
            count, cursor = read_uleb(data, body_start)
            for _ in range(count):
                module_len, cursor = read_uleb(data, cursor)
                module = data[cursor:cursor + module_len].decode("utf-8")
                cursor += module_len
                name_len, cursor = read_uleb(data, cursor)
                name = data[cursor:cursor + name_len].decode("utf-8")
                cursor += name_len
                kind = data[cursor]
                cursor += 1
                if kind == 0:
                    type_index, cursor = read_uleb(data, cursor)
                    imports.append({"module": module, "name": name, "kind": "function", "type": type_index})
                elif kind == 1:
                    cursor += 1  # element type
                    cursor = skip_limits(data, cursor)
                    imports.append({"module": module, "name": name, "kind": "table"})
                elif kind == 2:
                    cursor = skip_limits(data, cursor)
                    imports.append({"module": module, "name": name, "kind": "memory"})
                elif kind == 3:
                    cursor += 1  # value type
                    cursor += 1  # mutability
                    imports.append({"module": module, "name": name, "kind": "global"})
                else:
                    raise BuildError(f"unsupported import kind {kind}")
            offset = body_end
        elif section_id == 5:
            memory_section = True
            offset = body_end
        elif section_id == 7:  # exports
            count, cursor = read_uleb(data, body_start)
            for _ in range(count):
                name_len, cursor = read_uleb(data, cursor)
                name = data[cursor:cursor + name_len].decode("utf-8")
                cursor += name_len
                kind = data[cursor]
                cursor += 1
                _index, cursor = read_uleb(data, cursor)
                kind_name = {0: "function", 1: "table", 2: "memory", 3: "global", 4: "tag"}[kind]
                exports.append({"name": name, "kind": kind_name})
            offset = body_end
        elif section_id == 11:  # data segments
            count, cursor = read_uleb(data, body_start)
            for _ in range(count):
                flags, cursor = read_uleb(data, cursor)
                if flags == 0:
                    cursor = skip_init_expr(data, cursor)
                elif flags == 2:
                    _memory_index, cursor = read_uleb(data, cursor)
                    cursor = skip_init_expr(data, cursor)
                length, cursor = read_uleb(data, cursor)
                data_bytes += length
                data_segments += 1
                data_segment_sizes.append(length)
                cursor += length
            offset = body_end
        else:
            offset = body_end
    return {
        "bytes": len(data),
        "sha256": sha256_bytes(data),
        "imports": imports,
        "exports": exports,
        "sections": sections,
        "data_segments": data_segments,
        "data_segment_sizes": data_segment_sizes,
        "data_bytes": data_bytes,
        "memory_section": memory_section,
    }


