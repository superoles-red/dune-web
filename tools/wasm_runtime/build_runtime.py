class CommandRunner:
    def __init__(self, build_dir: Path, env_wrapper: Path, verbose: bool = False):
        self.logs_dir = build_dir / "logs"
        self.logs_dir.mkdir(parents=True, exist_ok=True)
        self.wrapper = env_wrapper
        self.verbose = verbose
        self.commands: list[dict] = []

    def run(self, name: str, argv: list[str], *, timeout: float = 1800.0, check: bool = True) -> subprocess.CompletedProcess:
        full = ["bash", str(self.wrapper), *argv]
        started = time.monotonic()
        try:
            result = subprocess.run(
                full,
                cwd=str(ROOT),
                capture_output=True,
                text=True,
                timeout=timeout,
            )
        except subprocess.TimeoutExpired as exc:
            (self.logs_dir / f"{name}.log").write_text(
                (exc.stdout or "") + "\n[TIMEOUT]\n" + (exc.stderr or ""), encoding="utf-8"
            )
            raise BuildError(f"command timed out after {timeout:.0f}s: {name}") from exc
        duration = time.monotonic() - started
        log_path = self.logs_dir / f"{name}.log"
        log_path.write_text(
            "$ " + " ".join(argv) + "\n\n" + result.stdout + "\n--- stderr ---\n" + result.stderr,
            encoding="utf-8",
        )
        self.commands.append(
            {"step": name, "argv": argv, "seconds": round(duration, 2), "returncode": result.returncode}
        )
        if self.verbose:
            sys.stdout.write(result.stdout)
            sys.stderr.write(result.stderr)
        if check and result.returncode != 0:
            tail = "\n".join((result.stdout + "\n" + result.stderr).splitlines()[-80:])
            raise BuildError(f"command failed ({result.returncode}): {name}\n{tail}\n(full log: {log_path})")
        return result


def make_emsdk_wrapper(build_dir: Path, emsdk: Path) -> Path:
    wrapper = build_dir / "emsdk_env.sh"
    wrapper.write_text(
        "#!/bin/bash\n"
        "# generated by tools/wasm_runtime/build_runtime.py\n"
        f'source "{emsdk}/emsdk_env.sh" >/dev/null 2>&1\n'
        'exec "$@"\n',
        encoding="utf-8",
    )
    wrapper.chmod(0o755)
    return wrapper


def emcc_version(runner: CommandRunner) -> str:
    result = runner.run("emcc-version", ["emcc", "--version"], timeout=300)
    match = re.search(r"(\d+)\.(\d+)\.(\d+)", result.stdout)
    if not match:
        raise BuildError("cannot parse emcc version")
    return ".".join(match.groups())


