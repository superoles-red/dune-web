#!/usr/bin/env python3
"""Build ``runtime/wasm/runtime.wasm`` -- the prebuilt Dune WASM runtime (Phase 1).

What the script does
--------------------
1. Reconstructs the *exact* pinned preamble (3 emitter lines + the pinned
   ``runtime/dune-runtime-v2.c`` + ``\\n``) in ``.local/wasm-runtime/preamble.c``
   and verifies its SHA-256 against ``runtime/manifest.json``.
2. Generates the ABI-descriptor C layout from ``abi_spec.py`` and the thin
   ABI/host layer from ``src/dune_rt_abi.inc``.
3. Regenerates the pinned YM2612 driver (vendor source + browser audio-levels
   adapter) exactly like ``tools/prepare_source.py`` and verifies its SHA-256
   against ``runtime/manifest.json``.
4. Compiles + links ``runtime.wasm`` with the pinned emcc 3.1.74 as a
   STANDALONE_WASM module with imported memory (JS owns the memory).
5. Builds the code-only ``stub_game.wasm`` test game module (clang wasm32 +
   wasm-ld, no libc/emscripten runtime, no data segment).
6. Generates ``loader.mjs``, instantiates the runtime in Node to dump and check
   the ABI descriptor, and writes ``runtime/wasm/manifest.json``.

The player ROM is never read by this script and never embedded: the runtime
allocates a 1 MiB ROM buffer on the heap in ``dune_rt_init()``.

Usage
-----
    python3 tools/wasm_runtime/build_runtime.py \
        --emsdk "/path/to/emsdk"

Only the Python standard library is required.  ``node`` is used to dump the
built module's ABI descriptor; without it the manifest's ``abi.actual`` block is
skipped (the Node test still validates it).
"""

