def portable_log(value, emsdk, build_dir):
    """Replace machine-specific prefixes so the manifest stays reproducible."""
    if isinstance(value, dict):
        return {key: portable_log(item, emsdk, build_dir) for key, item in value.items()}
    if isinstance(value, list):
        return [portable_log(item, emsdk, build_dir) for item in value]
    if isinstance(value, str):
        text = value
        for prefix, token in ((str(Path(build_dir).resolve()) + "/", "<build>/"),
                              (str(Path(emsdk).resolve()) + "/", "<emsdk>/"),
                              (str(ROOT) + "/", "<repo>/")):
            text = text.replace(prefix, token)
        return text
    return value

def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--emsdk", help="path to the pinned emsdk 3.1.74 checkout (or set EMSDK)")
    parser.add_argument("--build-dir", default=str(DEFAULT_BUILD_DIR),
                        help="staging/build directory (default: .local/wasm-runtime)")
    parser.add_argument("--out-dir", default=str(DEFAULT_OUT_DIR),
                        help="artifact directory (default: runtime/wasm)")
    parser.add_argument("--node", help="node executable used for the ABI dump (default: node from PATH)")
    parser.add_argument("--skip-abi-dump", action="store_true",
                        help="do not instantiate the runtime in Node while building")
    parser.add_argument("--allow-emcc-version", action="store_true",
                        help="do not require exactly emcc 3.1.74")
    parser.add_argument("--clean", action="store_true", help="remove previous generated files first")
    parser.add_argument("--verbose", action="store_true", help="stream compiler output")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        manifest = build(args)
    except BuildError as exc:
        print(f"build failed: {exc}", file=sys.stderr)
        return 1
    wasm = manifest["wasm"]
    print()
    print("runtime.wasm   ", wasm["bytes"], "bytes")
    print("sha256         ", wasm["sha256"])
    print("emcc           ", manifest["emcc"]["version"], "(standalone wasm, imported memory)")
    print("abi            ", f"{manifest['abi']['word_count']} words, abi_hash {manifest['abi']['abi_hash']}")
    print("exports        ", len(manifest["exports"]["all"]))
    print("deterministic  ", wasm["deterministic"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
