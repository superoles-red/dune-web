def verify_inputs(runtime_manifest: dict) -> dict:
    runtime_c = ROOT / "runtime" / "dune-runtime-v2.c"
    data = runtime_c.read_bytes()
    actual_sha = sha256_bytes(data)
    if actual_sha != runtime_manifest["runtime_sha256"]:
        raise BuildError(
            f"runtime/dune-runtime-v2.c SHA mismatch: {actual_sha} != {runtime_manifest['runtime_sha256']}"
        )
    if len(data) != runtime_manifest["runtime_bytes"]:
        raise BuildError("runtime/dune-runtime-v2.c size mismatch")

    adapters_dir = ROOT / "runtime" / "adapters"
    adapters_manifest = read_json(adapters_dir / "manifest.json")
    if adapters_manifest["count"] != runtime_manifest["adapters"]["count"]:
        raise BuildError("adapter count mismatch between manifests")
    for entry in adapters_manifest["files"]:
        path = adapters_dir / entry["name"]
        if not path.is_file():
            raise BuildError(f"missing adapter: {path}")
        blob = path.read_bytes()
        if len(blob) != entry["bytes"] or sha256_bytes(blob) != entry["sha256"]:
            raise BuildError(f"adapter SHA/size mismatch: {entry['name']}")

    audio_src = ROOT / "vendor" / "rearrakis" / "genesis_recompiler" / "audio_ymfm.cpp"
    audio_adapter = ROOT / "runtime" / "adapters" / "em_web_audio_levels_cpp.h"
    if not audio_src.is_file():
        raise BuildError(f"missing vendor audio driver: {audio_src}")
    if not audio_adapter.is_file():
        raise BuildError(f"missing audio-levels adapter: {audio_adapter}")

    return {
        "runtime_c": runtime_c,
        "adapters_dir": adapters_dir,
        "audio_src": audio_src,
        "audio_adapter": audio_adapter,
    }


def prepare_preamble(build_dir: Path, runtime_c: Path, runtime_manifest: dict) -> dict:
    preamble = GENERATED_PREFIX.encode("utf-8") + runtime_c.read_bytes() + b"\n"
    expected_sha = runtime_manifest["full_preamble_sha256"]
    if sha256_bytes(preamble) != expected_sha:
        raise BuildError(
            "reconstructed full preamble SHA-256 mismatch: "
            f"{sha256_bytes(preamble)} != {expected_sha}"
        )
    path = build_dir / "preamble.c"
    path.write_bytes(preamble)
    return {
        "path": path,
        "sha256": sha256_bytes(preamble),
        "bytes": len(preamble),
        "generated_prefix_sha256": sha256_bytes(GENERATED_PREFIX.encode("utf-8")),
        "generated_prefix_bytes": len(GENERATED_PREFIX.encode("utf-8")),
    }


def prepare_abi_sources(build_dir: Path) -> dict:
    layout = abi_spec.render_layout_header()
    fill = abi_spec.render_fill_include()
    layout_path = build_dir / "dune_abi_layout.h"
    fill_path = build_dir / "dune_abi_fill.inc"
    layout_path.write_text(layout, encoding="utf-8")
    fill_path.write_text(fill, encoding="utf-8")
    return {
        "layout_path": layout_path,
        "fill_path": fill_path,
        "layout_sha256": sha256_bytes(layout.encode("utf-8")),
        "fill_sha256": sha256_bytes(fill.encode("utf-8")),
    }


def prepare_audio_driver(build_dir: Path, audio_src: Path, audio_adapter: Path, runtime_manifest: dict) -> dict:
    """Reproduce tools/prepare_source.py's audio patch byte-for-byte."""
    text = audio_src.read_text(encoding="utf-8")
    needle = "class GenesisYM final : public ymfm::ymfm_interface {"
    if text.count(needle) != 1:
        raise BuildError("vendor audio driver layout changed (GenesisYM anchor)")
    text = text.replace(needle, audio_adapter.read_text(encoding="utf-8") + "\n" + needle, 1)

    needle = "ymfm::ym2612 chip;"
    if text.count(needle) != 1:
        raise BuildError("vendor audio driver layout changed (chip anchor)")
    text = text.replace(needle, "DuneOutputYM2612 chip;", 1)

    needle = "int32_t((int64_t(current.data[i])-previous.data[i])*fraction/144);"
    if text.count(needle) != 1:
        raise BuildError("vendor audio driver layout changed (level_output anchor)")
    text = text.replace(
        needle,
        needle + "\n        for(unsigned i=0;i<2;++i)stereo[i]=chip.level_output(i,fraction,stereo[i]);",
        1,
    )

    needle = 'extern "C" void genesis_ymfm_destroy(void *chip)'
    if text.count(needle) != 1:
        raise BuildError("vendor audio driver layout changed (destroy anchor)")
    additions = """extern "C" void genesis_ymfm_output_levels(void *chip,const unsigned levels[6]) {
    if(!chip||!levels)return;
    auto &g=*static_cast<GenesisYM*>(chip);
    bool changed=false;
    for(unsigned c=0;c<6;++c){
        unsigned value=levels[c];
        switch(value){
            case 0:case 10:case 25:case 50:case 100:break;
            default:value=100;
        }
        changed|=g.chip.levels[c]!=value;
        g.chip.levels[c]=value;
    }
    if(changed){g.chip.common_level=int(g.chip.levels[0]);for(unsigned c=1;c<6;++c)if(g.chip.levels[c]!=g.chip.levels[0])g.chip.common_level=-1;}
}
"""
    text = text.replace(needle, additions + needle, 1)

    blob = text.encode("utf-8")
    actual_sha = sha256_bytes(blob)
    if actual_sha != runtime_manifest["prepared_audio_sha256"]:
        raise BuildError(
            "prepared YM2612 driver SHA-256 mismatch: "
            f"{actual_sha} != {runtime_manifest['prepared_audio_sha256']}"
        )
    if len(blob) != runtime_manifest["prepared_audio_bytes"]:
        raise BuildError("prepared YM2612 driver size mismatch")
    path = build_dir / "audio_patched.cpp"
    path.write_bytes(blob)
    return {"path": path, "sha256": actual_sha, "bytes": len(blob)}


def write_runtime_c(build_dir: Path) -> Path:
    runtime_c = build_dir / "runtime.c"
    runtime_c.write_text(
        "/* Generated by tools/wasm_runtime/build_runtime.py -- do not edit. */\n"
        "/* 1. exact pinned preamble (3 emitter lines + runtime/dune-runtime-v2.c) */\n"
        '#include "preamble.c"\n'
        "/* 2. ABI / host-glue layer (no game data, no translated instructions) */\n"
        '#include "dune_rt_abi.inc"\n',
        encoding="utf-8",
    )
    return runtime_c


