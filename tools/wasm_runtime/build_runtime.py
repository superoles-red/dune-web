def resolve_emsdk(value: str | None) -> Path:
    if value:
        path = Path(value).expanduser().resolve()
    else:
        env = os.environ.get("EMSDK")
        if not env:
            raise BuildError("--emsdk is required (or set EMSDK)")
        path = Path(env).expanduser().resolve()
    if not (path / "emsdk_env.sh").is_file():
        raise BuildError(f"{path} does not look like an emsdk install (no emsdk_env.sh)")
    return path


